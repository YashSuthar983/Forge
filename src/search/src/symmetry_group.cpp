using model::Rational;
using Clock = core::SolverClock;
std::size_t sz(Index j) { return static_cast<std::size_t>(j); }
struct Edge {
  Index to;
  Rational coefficient;
};
struct Signature {
  Index color;
  std::vector<std::pair<Index, Rational>> neighbors;
  bool operator<(const Signature &other) const {
    return color != other.color ? color < other.color
                                : neighbors < other.neighbors;
  }
};
// No dense row cliques. Both sides are colored with the SAME intern table:
// a histogram mismatch proves that this partial correspondence cannot extend.
bool refine(const std::vector<std::vector<Edge>> &graph,
            std::vector<Index> &left, std::vector<Index> &right,
            const auto &expired) {
  const auto count = graph.size();
  for (;;) {
    if (expired())
      return false;
    std::map<Signature, Index> intern;
    std::vector<Index> next_left(count), next_right(count);
    const auto recolor = [&](const auto &color, auto &next) {
      for (std::size_t v = 0; v < count; ++v) {
        Signature key{color[v], {}};
        key.neighbors.reserve(graph[v].size());
        for (const auto &e : graph[v])
          key.neighbors.emplace_back(color[sz(e.to)], e.coefficient);
        std::sort(key.neighbors.begin(), key.neighbors.end());
        auto [it, inserted] = intern.try_emplace(
            std::move(key), static_cast<Index>(intern.size()));
        (void)inserted;
        next[v] = it->second;
        core::work_add(graph[v].size() + 1, core::WorkTag::Symmetry);
      }
    };
    recolor(left, next_left);
    recolor(right, next_right);
    std::vector<Index> a(intern.size(), 0), b(intern.size(), 0);
    for (Index c : next_left)
      ++a[sz(c)];
    for (Index c : next_right)
      ++b[sz(c)];
    if (a != b)
      return false;
    const Index old_count = *std::max_element(left.begin(), left.end()) + 1;
    left.swap(next_left);
    right.swap(next_right);
    // Refinement never merges classes. Only the partition's size matters,
    // not the transient IDs generated by the intern table.
    if (intern.size() == sz(old_count))
      return true;
  }
}
