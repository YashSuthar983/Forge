void VerifiedSymmetryGroup::build(const model::LpProblem &lp,
                                  const std::vector<Orbit> &candidates,
                                  double time_limit_s, std::vector<Index> order,
                                  const core::CancelToken *cancel) {
  generators_.clear();
  leaders_.clear();
  const Index n = lp.n_cols(), m = lp.n_rows(), total = n + m;
  order_ = std::move(order);
  if (order_.empty()) {
    order_.resize(sz(n));
    std::iota(order_.begin(), order_.end(), 0);
  }
  auto sorted = order_;
  std::sort(sorted.begin(), sorted.end());
  if (sorted.size() != sz(n))
    throw std::invalid_argument("symmetry order size");
  for (Index j = 0; j < n; ++j)
    if (sorted[sz(j)] != j)
      throw std::invalid_argument("symmetry order is not a permutation");
  for (const auto &cell : candidates)
    for (Index j : cell.cols)
      if (j < 0 || j >= n)
        throw std::invalid_argument("symmetry candidate column");
  if (n == 0 || candidates.empty() || core::cancel_requested(cancel))
    return;
  const auto started = Clock::now();
  const auto expired = [&] {
    return core::cancel_requested(cancel) ||
           (time_limit_s > 0 &&
            std::chrono::duration<double>(Clock::now() - started).count() >=
                time_limit_s);
  };
  SymmetryVerifier verifier(lp);
  std::vector<std::vector<Edge>> graph(sz(total));
  std::vector<Index> initial(sz(total));
  // Exact labels for boxes, objective and type. Rows are a different vertex
  // type; infinite sides retain their signed identity through Rational-free
  // binary64 tuples (input numbers are compared exactly, never with tol).
  using Label = std::tuple<int, f64, f64, f64, bool>;
  std::map<Label, Index> labels;
  const auto label = [&](const Label &key) {
    return labels.try_emplace(key, static_cast<Index>(labels.size()))
        .first->second;
  };
  for (Index j = 0; j < n; ++j)
    initial[sz(j)] = label({0, lp.col_lo[sz(j)], lp.col_hi[sz(j)], lp.c[sz(j)],
                            !lp.is_integer.empty() && lp.is_integer[sz(j)]});
  const auto &rp = lp.A.pattern.row_ptr();
  const auto &ci = lp.A.pattern.col_idx();
  for (Index i = 0; i < m; ++i) {
    if (expired())
      return;
    initial[sz(n + i)] =
        label({1, lp.row_lo[sz(i)], lp.row_hi[sz(i)], 0, false});
    std::map<Index, Rational> row;
    for (auto k = rp[sz(i)]; k < rp[sz(i) + 1]; ++k)
      row[ci[static_cast<std::size_t>(k)]] +=
          Rational(lp.A.vals[static_cast<std::size_t>(k)]);
    for (const auto &[j, a] : row)
      if (a != 0) {
        graph[sz(j)].push_back({n + i, a});
        graph[sz(n + i)].push_back({j, a});
      }
  }
  std::vector<int> sign(sz(n), 1);
  std::vector<f64> shift(sz(n), 0);
  // Explicit DFS frames avoid a recursion-depth dependency on model size.
  struct Frame {
    std::vector<Index> left, right, choices;
    Index source;
    std::size_t next = 0;
  };
  const auto find_action = [&](Index source,
                               Index target) -> std::vector<Index> {
    auto left = initial, right = initial;
    const Index unique = static_cast<Index>(labels.size());
    left[sz(source)] = unique;
    right[sz(target)] = unique;
    std::vector<Frame> stack;
    for (;;) {
      bool consistent = refine(graph, left, right, expired);
      if (expired())
        return {};
      if (consistent) {
        std::map<Index, std::vector<Index>> lcell, rcell;
        for (Index v = 0; v < total; ++v) {
          lcell[left[sz(v)]].push_back(v);
          rcell[right[sz(v)]].push_back(v);
        }
        // Arbitrary within-cell matching is only a proposal; identical
        // columns often complete here without individualizing them all.
        std::vector<Index> image(sz(n), -1);
        for (const auto &[c, cell] : lcell)
          for (std::size_t q = 0; q < cell.size(); ++q)
            if (cell[q] < n)
              image[sz(cell[q])] = rcell[c][q];
        if (verifier.verifies(image, sign, shift))
          return image;
        const std::vector<Index> *selected = nullptr;
        Index selected_color = -1;
        for (const auto &[c, cell] : lcell)
          if (cell.size() > 1 &&
              (!selected || cell.size() < selected->size())) {
            selected = &cell;
            selected_color = c;
          }
        if (selected)
          stack.push_back(
              {left, right, rcell[selected_color], selected->front(), 0});
      }
      // Dead end or a new frame: continue an untried image of its source.
      while (!stack.empty() && stack.back().next == stack.back().choices.size())
        stack.pop_back();
      if (stack.empty())
        return {};
      auto &frame = stack.back();
      left = frame.left;
      right = frame.right;
      const Index c = *std::max_element(left.begin(), left.end()) + 1;
      left[sz(frame.source)] = c;
      right[sz(frame.choices[frame.next++])] = c;
    }
  };
  std::vector<Index> generated_orbit(sz(n));
  std::iota(generated_orbit.begin(), generated_orbit.end(), 0);
  const auto orbit_root = [&](Index j) {
    while (generated_orbit[sz(j)] != j) {
      generated_orbit[sz(j)] = generated_orbit[sz(generated_orbit[sz(j)])];
      j = generated_orbit[sz(j)];
    }
    return j;
  };
  for (const auto &cell : candidates) {
    if (cell.cols.size() < 2)
      continue;
    const Index anchor = cell.cols.front();
    for (std::size_t q = 1; q < cell.cols.size() && !expired(); ++q) {
      const Index target = cell.cols[q];
      if (initial[sz(anchor)] != initial[sz(target)] ||
          orbit_root(anchor) == orbit_root(target))
        continue; // compositions of already verified actions connect this pair
      auto image = find_action(anchor, target);
      if (!image.empty() && std::find(generators_.begin(), generators_.end(),
                                      image) == generators_.end()) {
        std::vector<std::pair<Index, Index>> leader;
        for (Index j : order_)
          if (j != image[sz(j)])
            leader.emplace_back(j, image[sz(j)]);
        leaders_.push_back(std::move(leader));
        for (Index j = 0; j < n; ++j)
          generated_orbit[sz(orbit_root(j))] = orbit_root(image[sz(j)]);
        generators_.push_back(std::move(image));
      }
    }
    if (expired())
      break;
  }
}

bool VerifiedSymmetryGroup::propagate(std::vector<f64> &lo,
                                      std::vector<f64> &hi, PropTrail *trail,
                                      int depth, std::uint64_t &moves) const {
  if (lo.size() != order_.size() || hi.size() != order_.size())
    throw std::invalid_argument("symmetry box size");
  for (const auto &leader : leaders_)
    for (const auto &[j, k] : leader) {
      // Earlier comparisons are forced equal. The next pair must satisfy
      // x_j >= x_k even when the eventual strict comparison is later.
      if (hi[sz(j)] < lo[sz(k)])
        return false;
      if (lo[sz(j)] > hi[sz(k)])
        break; // strict prefix satisfies this leader
      if (lo[sz(j)] < lo[sz(k)]) {
        write_domain_bound(lo, hi, j, BoundDir::Lower, lo[sz(k)],
                           trail, {ReasonKind::Symmetry, -1, depth});
        ++moves;
      }
      if (hi[sz(k)] > hi[sz(j)]) {
        write_domain_bound(lo, hi, k, BoundDir::Upper, hi[sz(j)],
                           trail, {ReasonKind::Symmetry, -1, depth});
        ++moves;
      }
      if (!(lo[sz(j)] == hi[sz(j)] && lo[sz(k)] == hi[sz(k)] &&
            lo[sz(j)] == lo[sz(k)]))
        break;
    }
  return true;
}
std::vector<Orbit>
VerifiedSymmetryGroup::stabilizer_orbits(const std::vector<f64> &lo,
                                         const std::vector<f64> &hi,
                                         double time_limit_s,
                                         const core::CancelToken* cancel,
                                         bool* complete) const {
  const auto n = order_.size();
  if (lo.size() != n || hi.size() != n)
    throw std::invalid_argument("stabilizer box size");
  if (complete) *complete = false;
  const auto start = Clock::now();
  const auto interrupted = [&] {
    return core::cancel_requested(cancel) || (time_limit_s > 0 &&
      std::chrono::duration<double>(Clock::now() - start).count() >= time_limit_s);
  };
  std::vector<Index> parent(n), identity(n), colors(n);
  std::iota(parent.begin(), parent.end(), 0);
  std::iota(identity.begin(), identity.end(), 0);
  const auto find = [&](Index j) {
    while (parent[sz(j)] != j) {
      parent[sz(j)] = parent[sz(parent[sz(j)])];
      j = parent[sz(j)];
    }
    return j;
  };
  std::map<std::pair<f64, f64>, Index> labels;
  for (std::size_t j = 0; j < n; ++j) {
    if (std::isnan(lo[j]) || std::isnan(hi[j]))
      throw std::invalid_argument("stabilizer NaN box");
    colors[j] = labels.try_emplace(std::pair{lo[j], hi[j]},
                                  static_cast<Index>(labels.size())).first->second;
  }
  // t maps the original coloring to this orbit state. On an edge t*g -> u,
  // h=(t*g)*u^-1 preserves the original coloring. Schreier's lemma says all
  // these h generate its entire stabilizer once the coloring orbit is closed.
  struct State { std::vector<Index> color, transversal, inverse; };
  std::vector<State> states;
  states.push_back({colors, identity, identity});
  std::map<std::vector<Index>, std::size_t> known;
  known.emplace(colors, 0);
  bool exhausted = true;
  for (std::size_t at = 0; at < states.size() && exhausted; ++at) {
    for (const auto& g : generators_) {
      if (interrupted()) { exhausted = false; break; }
      std::vector<Index> next(n), action(n);
      for (std::size_t j = 0; j < n; ++j) {
        next[j] = states[at].color[sz(g[j])];
        action[j] = states[at].transversal[sz(g[j])];
      }
      auto [it, inserted] = known.try_emplace(next, states.size());
      if (inserted) {
        std::vector<Index> inverse(n);
        for (std::size_t j = 0; j < n; ++j) inverse[sz(action[j])] = static_cast<Index>(j);
        states.push_back({std::move(next), std::move(action), std::move(inverse)});
      } else {
        const auto& inverse = states[it->second].inverse;
        for (std::size_t j = 0; j < n; ++j) {
          const Index image = action[sz(inverse[j])];
          if (colors[j] != colors[sz(image)])
            throw std::logic_error("Schreier stabilizer coloring invariant");
          parent[sz(find(static_cast<Index>(j)))] = find(image);
        }
      }
      core::work_add(3 * n, core::WorkTag::Symmetry);
    }
  }
  if (complete) *complete = exhausted;
  std::map<Index, Orbit> cells;
  for (std::size_t j = 0; j < n; ++j)
    cells[find(static_cast<Index>(j))].cols.push_back(static_cast<Index>(j));
  std::vector<Orbit> result;
  for (auto &[id, cell] : cells) {
    (void)id;
    if (cell.cols.size() > 1) result.push_back(std::move(cell));
  }
  return result;
}
